    a.previous_last_email_send_date,
    a.previous_sms_click_cnt,
    a.previous_sms_click_cnt_14,
    a.previous_sms_click_cnt_30,
    a.previous_sms_click_cnt_90,
    a.previous_sms_click_cnt_180,
    a.previous_first_sms_click_date,
    a.previous_last_sms_click_date,
    a.previous_email_click_cnt,
    a.previous_email_click_cnt_14,
    a.previous_email_click_cnt_30,
    a.previous_email_click_cnt_90,
    a.previous_email_click_cnt_180,
    a.previous_first_email_click_date,
    a.previous_last_email_click_date,
    a.previous_email_open_cnt,
    a.previous_email_open_cnt_14,
    a.previous_email_open_cnt_30,
    a.previous_email_open_cnt_90,
    a.previous_email_open_cnt_180,
    a.previous_first_email_open_date,
    a.previous_last_email_open_date,
    a.previous_application_date,
    a.previous_application_status,
    a.previous_assessment_status,
    a.previous_dispersal_date,
    a.previous_settled_date,
    a.previous_first_sms_send_interval,
    a.previous_last_sms_send_interval,
    a.previous_first_email_send_interval,
    a.previous_last_email_send_interval,
    a.previous_first_sms_click_interval,
    a.previous_last_sms_click_interval,
    a.previous_first_email_click_interval,
    a.previous_last_email_click_interval,
    a.previous_first_email_open_interval,
    a.previous_last_email_open_interval,
    a.previous_application_interval,
    a.previous_dispersal_interval,
    a.previous_settlement_interval,
    a.age,
    a.bounce_flag,
    a.open_flag,
    a.click_flag,
    a.unsubscribe_flag,
    a.complaint_flag,
    CASE WHEN app.application_id IS NOT NULL THEN 1 ELSE 0 END AS application_flag,
    CASE WHEN app.dispersal_date IS NOT NULL AND application_status='4.Funded' THEN 1 ELSE 0 END AS dispersal_flag,
    app.application_id,
    app.application_time,
    EXTRACT(HOUR FROM app.application_time) AS application_hour,
    DATE(app.application_date) AS application_date,
    app.application_week,
    app.application_month,
    DATE(app.dispersal_date) AS dispersal_date,
    app.dispersal_week,
    app.dispersal_month,
    DATEDIFF(DATE(app.application_date), a.launch_date) AS response_day,
    DATEDIFF(DATE(app.dispersal_date), a.launch_date) AS conversion_day,
    app.traffic_source,
    app.app_platform,
    app.app_start_type,
