CREATE TABLE IF NOT EXISTS ba.iterable_responses AS
SELECT 
    a.campaign_id,
    a.campaign_name,
    a.message_medium,
    a.audience,
    a.email_type,
    a.launch_time,
    a.launch_hour,
    a.launch_date,
    a.launch_dow,
    a.launch_week,
    a.launch_month,
    a.template_id, 
    a.sms_template, 
    a.email_template_subject, 
    a.email_template_preheader,
    a.user_id,
    a.rendered_sms_message, 
    a.sms_send_count,
    a.ls_application_tag,
    a.ls_user_tag,
    a.previous_sms_send_cnt,
    a.previous_sms_send_cnt_14,
    a.previous_sms_send_cnt_30,
    a.previous_sms_send_cnt_90,
    a.previous_sms_send_cnt_180,
    a.previous_first_sms_send_date,
    a.previous_last_sms_send_date,
    a.previous_email_send_cnt,
    a.previous_email_send_cnt_14,
    a.previous_email_send_cnt_30,
    a.previous_email_send_cnt_90,
    a.previous_email_send_cnt_180,
