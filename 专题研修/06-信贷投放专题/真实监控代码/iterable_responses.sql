    app.app_side_complete_type,
    app.completed_step,
    app.last_step,
    app.application_status,
    app.assessment_status,
    app.risk_level,
    app.finv_color_code,
    app.term_change_tag,
    app.reschedule_tag,
    app.attributed_utm,
    app.attributed_category,
    app.attributed_medium,
    app.attributed_campaign,
    app.total_amount as loan_amount,
    app.total_loan_amount,
    app.repayment_frequency,
    app.application_tag,
    app.user_tag,
    app.loan_tag,
    app.requested_loan_amount,
    app.requested_loan_tag,
    app.original_term_length,
    app.actual_term_length,
    app.original_term_avg,
    app.actual_term_avg,
    app.zip_code,
    app.suburb,
    app.state,
    app.family_type,
    app.dependents,
    app.total_income,
    app.total_expenses,
    app.gross_surplus,
    app.net_surplus,
    app.default_income,
    app.default_expenses,
    app.default_gross_surplus,
    app.approval_rules_decision,
    app.combined_ml_models_decision,
    app.is_auto_approved,
    app.is_bad_loan,
    app.approval_rules,
    app.combined_reasons,
    app.final_probability,
    app.base_probability,
    app.dpd_7_probability,
    app.dpd_14_probability,
    app.dpd_21_probability,
    app.dpd_28_probability,
    app.dpd_35_probability,
    app.dpd_42_probability,
    app.dpd_49_probability,
    app.LTI,
    app.PTI
FROM ba.iterable_targeting_history a
LEFT JOIN 
    (SELECT *, CAST(campaign_id AS BIGINT) AS campaign_id_numeric
    FROM
        (SELECT *,
             ROW_NUMBER() OVER(PARTITION BY user_id, campaign_id ORDER BY application_status DESC, application_time DESC) AS sep_no
        FROM 
            (SELECT *,
                 CASE WHEN LENGTH(attributed_campaign)=17 AND attributed_campaign rlike 'campaign_' THEN RIGHT(attributed_campaign,8)
                      ELSE LEFT(attributed_campaign,8) END AS campaign_id
            FROM ba.customer_profile_rawdata
            WHERE attributed_utm IN ('Iterable', 'sms', 'email')
            AND attributed_campaign IS NOT NULL AND attributed_campaign<>'Null'
            ) AS app
        WHERE campaign_id<>'campaign'
        ) AS app
    WHERE sep_no=1) AS app
ON a.user_id=app.user_id
AND a.campaign_id=app.campaign_id_numeric
ORDER BY a.launch_date, a.campaign_name, a.user_id
;